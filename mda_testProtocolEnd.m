function ok = mda_testProtocolEnd()
%MDA_TESTPROTOCOLEND  Test of the end of protocols without end comment (mda_protocols) with a synthetic recording
%(9 channels, 400 Hz, 2400 s; stimuli of channels 1 and 2 in the status channel).
%
%   ok = mda_testProtocolEnd()   prints the single checks, returns true if all pass
%
%      0- 300 s  0.5 Hz, 60 mA (regular)
%    300 s       'start stimCurrent threshold protocol': current steps 20, 30, 40, 50, 70, 80 mA every 40 s
%    540-1000    0.5 Hz, 60 mA                    --> ST ends at 540 s (regular pacing)
%   1000 s       'start post rest potentiation protocol': 3 trains of 10 stimuli (0.5 Hz), 30 s pauses
%   1150 s       'start FFR protocol': 1 Hz, 2 Hz (100 s each)   --> PRP ends at 1150 s (next protocol)
%   1350-2400    0.5 Hz, 60 mA                    --> FFR ends at 1350 s (regular pacing)
%   1800 s       'start pulse duration protocol': pulse duration (log chargeDuration) 1000, 500, 250, 2000 us
%                every 30 s, interval and current unchanged   --> PD ends at 1890 s (pulse duration unchanged)
% Second recording (2026-10-11): protocol keywords of comments (unknown type, StimThresh) and interruptions (software
% restart, connection lost). Pendant of py/tests/test_protocol_end.py (same recordings and checks).
% Example event logs of the control software (py/tests/event_logs_2_2, 2026-10-20): waiting lines, pairing of the
% automatic comments with the next protocolRun line, code backup.
%
% TS 2026-10-10 (example logs of the control software 2026-10-20)

% MyoDishAnalysis (https://github.com/TS-IVS/MyoDishAnalysis)
% Copyright (c) 2026 Thomas Seidel
% SPDX-License-Identifier: GPL-3.0-or-later
% Additional terms (GPL-3.0 section 7): see the file NOTICE

ok = true;
T = 2400; fs = 400;
folder = tempname; mkdir(folder);
cleanup = onCleanup(@() rmdir(folder, 's')); %#ok<NASGU>
f = fullfile(folder, 'pend_rigA_0.mdd');
writeRecording(f, T, fs);
P = mda_protocols(f);
ok = check(ok, 'types and starts', isequal(P.type', {'ST', 'PRP', 'FFR', 'PD'}) && ...
    isequal(P.from', [300 1000 1150 1800]));
ok = check(ok, 'estimated ends: regular pacing, next protocol, regular pacing, pulse duration unchanged', ...
    max(abs(P.to' - [540 1150 1350 1890])) < 1e-9);
ok = check(ok, 'notes', ...
    strcmp(P.note{1}, 'no end comment: end estimated at 540 s (start of regular pacing: 0.5 Hz, 60 mA, > 5 min)') && ...
    strcmp(P.note{2}, 'no end comment: end estimated at 1150 s (start of the next protocol ''FFR protocol'')') && ...
    strcmp(P.note{3}, ['no end comment: end estimated at 1350 s (start of regular pacing: 0.5 Hz, 60 mA, ' ...
    '> 5 min)']) && ...
    strcmp(P.note{4}, ['no end comment: end estimated at 1890 s (start of regular pacing: 0.5 Hz, 60 mA, ' ...
    '> 5 min)']));
L = mda_protocols(strrep(f, '.mdd', '_log.log'));
ok = check(ok, 'log file only: next protocol or end of the file', ...
    max(abs(L.to(1:3)' - [1000 1150 1800])) < 1e-9 && ...
    isinf(L.to(4)) && strcmp(L.note{4}, 'no end comment: end estimated at Inf s (end of the file)'));
P0 = mda_protocols(f, 0);
ok = check(ok, 'without the end estimation from the stimuli', max(abs(P0.to' - [1000 1150 1800 T])) < 1e-9 && ...
    strcmp(P0.note{4}, sprintf('no end comment: end estimated at %d s (end of the file)', T)));
% 2026-10-11: comments without protocol keyword are no protocol; 'StimThresh' = ST; a protocol of unknown type needs
% an end comment or regular pacing; a software restart ends a protocol without end comment, a connection lost for 1 s
% does not
f2 = fullfile(folder, 'pkw_rigA_0.mdd');
writeRecording(f2, T, fs, {100, 0, 'comment', 'Software new started'; 300, 0, 'comment', 'Start StimThresh'; ...
    600, 0, 'comment', 'not sure if stim protocol started'; ...
    1000, 0, 'comment', 'start post rest potentiation protocol'; 1150, 0, 'comment', 'start FFR protocol'; ...
    1200, 0, 'event', 'Connection lost'; 1201, 0, 'event', 'Connection re-established'; ...
    1250, 0, 'Event', 'LogFile opened: C:/x/pkw_rigA_0_log.log'; 1250, 0, 'programInfo', 'Version 2.0.1'; ...
    1800, 0, 'comment', 'start training programme'; 1830, 0, 'comment', 'end of training programme'; ...
    2100, 0, 'event', 'Connection lost'});
P2 = mda_protocols(f2);
ok = check(ok, 'keywords: no protocol without keyword, StimThresh = ST, unknown type', ...
    isequal(P2.type', {'ST', 'PRP', 'FFR', 'unknown'}) && isequal(P2.from', [300 1000 1150 1800]) && ...
    strcmp(P2.groupBy{4}, 'none') && strcmp(P2.name{4}, 'training programme'));
ok = check(ok, 'interruptions: software restart ends the FFR, a connection lost for 1 s does not', ...
    max(abs(P2.to' - [540 1150 1250 1830])) < 1e-9 && ...
    strcmp(P2.note{3}, 'no end comment: end estimated at 1250 s (software restarted)'));
% 2026-10-11: a protocol outside the recorded data is not analysed (note), the others are
P3 = [P; P(3,:)];
P3.number(5) = 2; P3.from(5) = 2500; P3.to(5) = 2600;
[~, ~, info] = MyoDishAnalysis(f, 1, [], [], 'protocol', P3, 'quiet', true);
ok = check(ok, 'protocol outside the recorded data: not analysed, the others are', ...
    any(strcmp(info.notes, 'protocol FFR 2: not analysed: outside the recorded data (2500 ... 2600 s, file length 2400.0 s)')) && ...
    isequal(info.rangeLabels(:)', {'ST 1', 'PRP 1', 'FFR 1', 'PD 1'}) && height(info.protocols) == 5 && ...
    contains(info.protocols.note{5}, 'not analysed: outside the recorded data'));
% 2026-10-18: structured events of the control software and protocols from protocolRun events (see the help)
f4 = fullfile(folder, 'dev_rigA_0.mdd');
writeRecording(f4, T, fs);
writeDevLog(f4, T);
V = mda_logEntries(strrep(f4, '.mdd', '_log.log'), 'events');
ok = check(ok, 'structured events: events, waiting, codes, one line cut off', ...
    V.Properties.UserData.nUnreadable == 1 && isequal(V.event', {'user', 'start', 'end', 'start', 'logOpen', ...
    'slice_state', 'slice_state', 'end', 'start', 'end', 'start', 'abort', 'start'}) && ...
    isequal(V.waiting', [true(1, 4) false(1, 9)]) && ...
    isequal(V.code(1:5)', {'system', 'protocolRun', 'protocolRun', 'protocolRun', 'system'}));
d7 = V.data{7};
ok = check(ok, 'structured events: channel, fields by name, null', isequal(V.channel(6:7)', [1 2]) && ...
    isequal(sort(fieldnames(d7))', sort({'v', 'event', 'actionId', 'by', 'kind'})) && strcmp(d7.kind, 'empty') && ...
    strcmp(V.by{5}, 'auto') && strcmp(V.data{5}.software, '2.1.9787.20360') && ...
    strcmp(V.data{9}.scheduleFile, 'st.txt') && isempty(V.data{2}.scheduleFile));
V0 = mda_logEntries(strrep(f, '.mdd', '_log.log'), 'events');
ok = check(ok, 'structured events: none in older logs', height(V0) == 0 && V0.Properties.UserData.nUnreadable == 0);
P4 = mda_protocols(f4);
ok = check(ok, 'protocolRun: types, names, times (comment protocol of the same type dropped)', ...
    isequal(P4.type', {'substance', 'ST', 'PRP', 'FFR', 'doseResponse'}) && ...
    isequal(P4.name', {'wash in', 'stim threshold', 'PRP 30 s', 'FFR protocol', 'iso DRC'}) && ...
    isequal(P4.from', [0 300 1002 1150 1800]) && max(abs(P4.to' - [200 540 1150 1350 T])) < 1e-9 && ...
    isequal(P4.groupBy', {'none', 'stimCurrent', 'pauseLength', 'pacingFrequency', 'none'}) && ...
    isequal(P4.number', [1 1 1 1 1]));
ok = check(ok, 'protocolRun: notes, start and end comments', isequal(P4.note', {['started before this recording ' ...
    '(2000-01-01 10:00:00)'], '', 'aborted: user', ['no end comment: end estimated at 1350 s (start of regular ' ...
    'pacing: 0.5 Hz, 60 mA, > 5 min)'], 'no end in the log: end of the file'}) && ...
    isequal(P4.startComment(1:3)', {'protocolRun start: wash in (manual)', ...
    'protocolRun start: stim threshold (schedule st.txt line 3)', ...
    'protocolRun start: PRP 30 s (schedule prp.txt line 2)'}) && ...
    isequal(P4.endComment(1:3)', {'protocolRun end: user', 'protocolRun end: protocolEnd', 'protocolRun abort: user'}));
f5 = fullfile(folder, 'drc_rigA_0.mdd');
writeRecording(f5, T, fs, {100, 0, 'comment', 'start Iso DRC protocol'; 200, 0, 'comment', 'end Iso DRC protocol'; ...
    300, 0, 'comment', 'start dose response FFR'; 400, 0, 'comment', 'end dose response FFR'});
P5 = mda_protocols(strrep(f5, '.mdd', '_log.log'));
ok = check(ok, 'names with dose response or DRC: doseResponse', isequal(P5.type', {'doseResponse', 'doseResponse'}) && ...
    isequal(P5.from', [100 300]) && isequal(P5.to', [200 400]) && isequal(P5.groupBy', {'none', 'none'}));
% 2026-10-20: 'post pause' and 'pause potentiation' are PRP keywords; comments of an older standard schedule without end
% comments: each protocol ends at the start of the next one
f6 = fullfile(folder, 'std_rigA_0.mdd');
writeRecording(f6, T, fs, {20, 0, 'comment', 'Start refractory period'; 1016, 0, 'comment', ...
    'Start post-pause-potentiation'; 1261, 0, 'comment', 'Start stimulation threshold'; 1873, 0, 'comment', ...
    'Start force-frequency relation'});
P6 = mda_protocols(strrep(f6, '.mdd', '_log.log'));
ok = check(ok, 'post pause: PRP; standard schedule without end comments', ...
    isequal(P6.type', {'RP', 'PRP', 'ST', 'FFR'}) && isequal(P6.from', [20 1016 1261 1873]) && ...
    isequal(P6.to(1:3)', [1016 1261 1873]) && ...
    isequal(P6.groupBy', {'S2interval', 'pauseLength', 'stimCurrent', 'pacingFrequency'}));
% 2026-10-20: example event logs of the control software (py/tests/event_logs_2_2, see its README)
ev = fullfile(fileparts(mfilename('fullpath')), 'py', 'tests', 'event_logs_2_2');
L = dir(fullfile(ev, '*', '*_log.log'));
pass = numel(L) == 26;
for i = 1:numel(L)
    E = mda_logEntries(fullfile(L(i).folder, L(i).name));
    V = mda_logEntries(E, 'events');
    op = find(strcmp(E.code, 'Event') & ~cellfun(@isempty, regexp(E.text, '^LogFile\d? (opened|created)', 'once')));
    w = find(V.waiting);
    for j = w(:)'
        k = op(find(op > V.row(j), 1));
        pass = pass && ~isempty(k) && V.t_file(j) == E.t_file(k);
    end
    pass = pass && V.Properties.UserData.nUnreadable == 0 && height(V) > 0;
end
ok = check(ok, 'example logs: all read, waiting lines at the time of the next opening', pass);
pf = fullfile(ev, 'recording_callers', 'p_log.log');
V = mda_logEntries(pf, 'events');
P6 = mda_protocols(pf);
ok = check(ok, 'example logs: second recording continued as main recording, both protocols', ~any(V.waiting) && ...
    isequal(P6.name', {'first protocol', 'second protocol'}) && isequal(P6.from', [0 2]) && isequal(P6.to', [2 4]));
V = mda_logEntries(fullfile(ev, 'recording_callers', 'c_log.log'), 'events');
W = V(V.waiting, :);
ok = check(ok, 'example logs: schedule run while no recording ran: time of LogFile created', ...
    isequal(W.event', {'start', 'reset'}) && isequal(W.t_logged', [7.25 7.25]) && isequal(W.t_file', [0 0]));
V = mda_logEntries(fullfile(ev, 'backup_update_conflict', 'd_00_log.log'), 'events');
V2 = mda_logEntries(fullfile(ev, 'backup_update_conflict', 'c_00_log.log'), 'events');
ok = check(ok, 'example logs: code backup, waiting backup lines, new run of the program', ...
    strcmp(V.code{1}, 'backup') && strcmp(V.event{1}, 'backup_copied') && V.waiting(1) && V.t_logged(1) == 9.9 && ...
    V.t_file(1) == 0 && isequal(V2.event(V2.waiting)', {'backup_setting', 'identity', 'backup_copied'}) && ...
    max(abs(V2.t_file(V2.waiting)' - [0 4.9 4.9])) < 1e-12);
V = mda_logEntries(fullfile(ev, 'recording_files', 'a_rockerStops_log.log'), 'events');
ok = check(ok, 'example logs: LogFile closed of the main log in a rocker stop log: no waiting lines', ~any(V.waiting));
src = fullfile(ev, 'protocol_new_form', 'a_log.log');
P7 = mda_protocols(src);
fid = fopen(src, 'r'); b = fread(fid, inf, 'uint8=>uint8')'; fclose(fid);
txt = char(double(b(3:2:end)) + 256 * double(b(4:2:end)));
lines = regexp(txt, '\r\n', 'split');
for i = 1:numel(lines)
    q = strsplit(lines{i}, ';');
    if numel(q) >= 5 && strcmp(q{4}, 'protocolRun')
        q{2} = sprintf('%d', str2double(q{2}) + 1500);
        lines{i} = strjoin(q, ';');
    end
end
f8 = fullfile(folder, 'shifted_log.log');
fid = fopen(f8, 'w'); fwrite(fid, [255 254], 'uint8');
u = double(strjoin(lines, sprintf('\r\n')));
fwrite(fid, [mod(u, 256); floor(u / 256)], 'uint8'); fclose(fid);
P8 = mda_protocols(f8);
ok = check(ok, 'example logs: protocolRun lines 1.5 s after their comments: same protocols', ...
    isequal(P7.type', {'FFR', 'ST', 'PD', 'other'}) && isequal(P8.name', P7.name') && ...
    max(abs(P8.from - P7.from - 1.5)) < 1e-9 && height(P8) == 4);
end


