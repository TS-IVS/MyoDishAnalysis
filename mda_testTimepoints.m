function ok = mda_testTimepoints()
%MDA_TESTTIMEPOINTS  Test of mda_timepoints with synthetic results of the watcher (csv files, folders of the series):
%experiment expT, series rigT_S, recordings 0 (day 1) and 1 (day 2) and a parallel recording of recording 0 (not used),
%treatment 2000-01-01 12:00:00, windows of 120 s at -60, 10, 120, 1440 and 2880 min.
%
%   ok = mda_testTimepoints()   prints the single checks, returns true if all pass
%
%   ch1  amplitude 100 before, 150 after the treatment (diastolic force 10 / 30 uN); one extra beat (amplitude 40) in
%        the baseline window; another slice on day 2
%   ch2  amplitude 200; chamber out 12:09:30-12:11:00 and a comment at 12:11:00 (window +10 min: 30 of ~60 contractions)
%   ch3  amplitude 300; alternans 300 / 150 from 13:30 (window +120 min); no contractions on day 2
%   protocol P1 13:59:00-14:03:00 (window +120 min), no data on day 3 (window +2880 min: pending)
%   all channels: dFdtMax 5000 uN/s (mda_timepoints: 5 mN/s); diastolic force of ch2 and ch3 50 uN
% Pendant of py/tests/test_timepoints.py (same files and checks).
%
% TS 2026-10-15 (means, SD, SEM, dF/dt in mN/s, diastolic force as change in uN, no contractions, images absolute and
% normalized 2026-10-16)

% MyoDishAnalysis (https://github.com/TS-IVS/MyoDishAnalysis)
% Copyright (c) 2026 Thomas Seidel
% SPDX-License-Identifier: GPL-3.0-or-later
% Additional terms (GPL-3.0 section 7): see the file NOTICE

ok = true;
res = tempname; mkdir(res);
cleanup = onCleanup(@() rmdir(res, 's')); %#ok<NASGU>
res = char(java.io.File(res).getCanonicalPath());
writeResults(res);
off = [-60 10 120 1440 2880];

TP = mda_timepoints(fullfile(res, 'expT'), 'T1', 'rigT_S', [], '2000-01-01 12:00', off);
S = TP.summary;
g = @(c, o) S(S.channel == c & S.offset_min == o, :);
ok = check(ok, 'channels [] = channels with contractions; 15 rows; baseline -60 min', ...
    isequal(TP.rows.channel', [1 2 3]) && height(S) == 15 && TP.baseline == -60);
ok = check(ok, 'sample ID: slice register (ch1), else the series name after the setup; group empty', ...
    isequal(TP.rows.sampleID', {'A1', 'S', 'S'}) && isequal(S.sampleID(1:5:end)', {'A1', 'S', 'S'}) && ...
    all(cellfun(@isempty, TP.rows.group)));
r = g(1, -60);
a0 = [100 * ones(60, 1); 40];                          %baseline ch1: 60 beats of 100 uN and the extra beat (included)
ok = check(ok, 'baseline ch1: 61 contractions (1 extra), mean, median 100; parallel recording not used', ...
    strcmp(r.from{1}, '2000-01-01 11:00:00') && strcmp(r.to{1}, '2000-01-01 11:02:00') && r.nBeats == 61 && ...
    r.nIncluded == 61 && r.nExtra == 1 && abs(r.amplitude - mean(a0)) < 1e-9 && r.amplitude_median == 100 && ...
    strcmp(r.recording{1}, 'rigT_S_0') && isempty(r.note{1}));
ok = check(ok, 'baseline ch1: SD, SEM, quartiles, diastolic force, dFdtMax in mN/s', ...
    abs(r.amplitude_SD - std(a0)) < 1e-9 && abs(r.amplitude_SEM - std(a0) / sqrt(61)) < 1e-9 && ...
    r.amplitude_q25 == 100 && r.amplitude_q75 == 100 && r.diastolicForce == 10 && r.dFdtMax == 5);
r = g(1, 10);
ok = check(ok, '+10 min ch1: 150 = 151.5 % of baseline, TTP90 120 %, diastole +20 uN', ...
    r.amplitude == 150 && abs(r.amplitude_pctBaseline - 15000 / mean(a0)) < 1e-9 && ...
    abs(r.TTP90_pctBaseline - 120) < 1e-9 && abs(r.dFdtMax_pctBaseline - 100) < 1e-9 && ...
    r.diastolicForce_delta == 20);
pars = {'amplitude', 'diastolicForce', 'TTP90', 'TTR90', 'CD50', 'CD90', 'dFdtMax', 'dFdtMin', 'AUC', ...
    'beatsPerMinute'};
nm = strcat(pars, '_pctBaseline'); nm{2} = 'diastolicForce_delta';
want = [{'series', 'channel', 'sampleID', 'group', 'time', 'offset_min', 'from', 'to', 'recording', 'slice', ...
    'nBeats', 'nIncluded', 'nExtra', 'note'}, reshape([pars; nm], 1, []), ...
    reshape([strcat(pars, '_SD'); strcat(pars, '_SEM')], 1, []), ...
    reshape([strcat(pars, '_median'); strcat(pars, '_q25'); strcat(pars, '_q75')], 1, []), ...
    {'nAvgBeats', 'avgBeat_diastolic', 'avgBeat_amplitude'}];
ok = check(ok, 'default parameters, units (dF/dt mN/s), columns of the summary', isequal(TP.parameters, pars) && ...
    isequal(TP.units(7:8), {'mN/s', 'mN/s'}) && isequal(S.Properties.VariableNames, want));
r = g(2, 10);
ok = check(ok, '+10 min ch2: chamber out, comment, 30 of ~60 contractions', r.nIncluded == 30 && strcmp(r.note{1}, ...
    'chamber out 12:09:30-12:11:00; comment 12:11:00 medium exchange; 30 of ~60 expected contractions included'));
ok = check(ok, '+120 min: protocol P1 in all channels', ...
    all(strcmp(S.note(S.offset_min == 120 & S.channel < 3), 'protocol P1 13:59:00-14:03:00')));
r = g(3, 120);
ok = check(ok, '+120 min ch3: alternans (note, mean = median = 225)', strcmp(r.note{1}, ['protocol P1 ' ...
    '13:59:00-14:03:00; alternans: 2 amplitude groups 150 / 300 uN (50 % small beats, 100 % of successive beats ' ...
    'switch)']) && r.amplitude == 225 && r.amplitude_median == 225);
ok = check(ok, 'no recordings: no average beats (note)', height(TP.averageBeats) == 0 && all(S.nAvgBeats == 0) && ...
    any(contains(TP.notes, 'rigT_S_0.mdd not found')));
r = g(1, 1440);
ok = check(ok, '+1440 min ch1: recording 1, slice 2: no pctBaseline', strcmp(r.recording{1}, 'rigT_S_1') && ...
    r.slice == 2 && r.amplitude == 150 && isnan(r.amplitude_pctBaseline) && ...
    strcmp(r.note{1}, 'other slice than in the baseline window'));
r = g(3, 1440);
ok = check(ok, '+1440 min ch3: no contractions: force values 0, times NaN, diastole from the signal (no mdd)', ...
    strcmp(r.note{1}, 'no contractions') && r.nBeats == 0 && r.amplitude == 0 && r.dFdtMax == 0 && r.AUC == 0 && ...
    r.beatsPerMinute == 0 && r.amplitude_pctBaseline == 0 && isnan(r.TTP90) && isnan(r.diastolicForce) && ...
    any(contains(TP.notes, 'diastolic force without contractions: rigT_S_1.mdd not found')));
ok = check(ok, '+2880 min: pending (no data yet)', all(strcmp(S.note(S.offset_min == 2880), 'pending: no data yet')));
ok = check(ok, 'matrices: beatsPerMinute 30.5 / NaN, amplitude, pctBaseline', ...
    isnan(TP.matrix.beatsPerMinute(1, 5)) && TP.matrix.beatsPerMinute(1, 1) == 30.5 && ...
    max(abs(TP.matrix.amplitude(:, 1)' - [mean(a0) 200 300])) < 1e-9 && ...
    max(abs(TP.pctBaseline.amplitude(1, 1:3) - [100 15000 / mean(a0) 15000 / mean(a0)])) < 1e-9);
C = TP.course; c1 = C(C.channel == 1, :);
ok = check(ok, 'course: 1-min values of day 1 and 2, % of baseline (medians), diastole, dFdtMax', ...
    c1.minutes(1) == -90 && c1.minutes(end) == 1619 && height(c1) == 570 && ...
    sum(c1.minutes >= -90 & c1.minutes <= 179) == 270 && c1.amplitude_pctBaseline(c1.minutes == -1) == 100 && ...
    c1.amplitude_pctBaseline(c1.minutes == 0) == 150 && c1.diastolicForce_delta(c1.minutes == 0) == 20 && ...
    all(c1.dFdtMax == 5));
ok = check(ok, 'beats: all contractions of the windows; units', height(TP.beats) == sum(S.nBeats) && ...
    strcmp(TP.units{1}, 'uN'));
d = fullfile(res, 'expT', 'timepoints', 'T1_2000-01-01-12-00');
D = dir(d); D = sort({D(~startsWith({D.name}, '.')).name});
b = 'T1_2000-01-01-12-00';
x = fullfile(d, [b '.xlsx']);
pass = strcmp(TP.folder, d) && isequal(D, sort(strcat(b, {'.xlsx', '_timepoints_abs.png', '_timepoints_abs.fig', ...
    '_timepoints_norm.png', '_timepoints_norm.fig', '_course_abs.png', '_course_abs.fig', '_course_norm.png', ...
    '_course_norm.fig'}))) && ...
    isequal(cellstr(sheetnames(x))', {'summary', 'matrix', 'course', 'beats', 'averageBeats', 'averageBeatsMean', ...
    'info'});
if pass
    M = readtable(x, 'Sheet', 'matrix', 'VariableNamingRule', 'preserve', 'TextType', 'char');
    v = @(p, m) M.('+10 min')(strcmp(M.parameter, p) & strcmp(M.measure, m) & M.channel == 1);
    pass = isequal(M.Properties.VariableNames(6:end), {'-60 min', '+10 min', '+120 min', '+1440 min', '+2880 min'}) ...
        && v('amplitude', 'mean') == 150 && abs(v('amplitude', 'pctBaseline') - 15000 / mean(a0)) < 1e-9 && ...
        v('diastolicForce', 'delta') == 20;
end
ok = check(ok, 'files: <experiment>/timepoints/T1_2000-01-01-12-00/ (xlsx, png, fig: abs, norm), matrix sheet', pass);

% inputs: one time per channel, seconds, no baseline, nothing written; matrix with one time per element; errors
TP = mda_timepoints(res, 'T2', 'rigT_S', [1 2], {'2000-01-01 12:00', '2000-01-01 12:01:00'}, [-60 10], 60, ...
    'baseline', nan, 'write', false, 'sampleID', 'X9', 'group', 'HTX');
ok = check(ok, 'options sampleID and group', isequal(TP.rows.sampleID', {'X9', 'X9'}) && ...
    all(strcmp(TP.summary.group, 'HTX')));
ok = check(ok, 'one time per channel, 60 s, no baseline, write false', isempty(TP.folder) && isempty(TP.files) && ...
    all(isnan(TP.pctBaseline.amplitude(:))) && isequal(TP.summary.from', {'2000-01-01 11:00:00', ...
    '2000-01-01 12:10:00', '2000-01-01 11:01:00', '2000-01-01 12:11:00'}) && ...
    isequal(TP.summary.nBeats', [31 30 30 30]));
TP = mda_timepoints(res, 'T6', 'rigT_S', 1, '2000-01-01 12:00', [-60 10], 'baseline', nan, 'averageBeats', false);
D = dir(TP.folder); D = sort({D(~startsWith({D.name}, '.')).name});
ok = check(ok, 'no baseline: only absolute images', isequal(D, sort(strcat('T6_2000-01-01-12-00', {'.xlsx', ...
    '_timepoints_abs.png', '_timepoints_abs.fig', '_course_abs.png', '_course_abs.fig'}))));
TP = mda_timepoints(res, 'T3', {'rigT_S'}, [3 0 1], {'2000-01-01 12:00', '', '01.01.2000 12:00:30'}, -60, ...
    'write', false);
ok = check(ok, 'channel matrix with one time per element', isequal(TP.rows.channel', [3 1]) && ...
    isequal(TP.rows.time', {'2000-01-01 12:00:00', '2000-01-01 12:00:30'}));
bad = {{'label', 'a b'}, {'offsets', []}, {'channels', [1 1]}, {'series', 'rigX'}, {'time', 'tomorrow'}, ...
    {'offsets', [-60 -60]}};
nErr = 0;
for i = 1:numel(bad)
    a = struct('label', 'T4', 'series', 'rigT_S', 'channels', 1, 'time', '2000-01-01 12:00', 'offsets', [-60 10]);
    a.(bad{i}{1}) = bad{i}{2};
    try
        mda_timepoints(res, a.label, a.series, a.channels, a.time, a.offsets, 'write', false);
    catch
        nErr = nErr + 1;
    end
end
ok = check(ok, 'errors: label, offsets, channel twice, series, time, offset twice', nErr == numel(bad));

% mda_poolTimepoints (2026-10-16): OME0.5uM (sample H1 ch1 + ch2, sample H3 ch2 on day 2) and CTRL (sample H2 ch3)
TPs = {mda_timepoints(res, 'OME0.5uM', 'rigT_S', [1 2], '2000-01-01 12:00', [-60 10], 'sampleID', 'H1', 'group', ...
    'HTX', 'averageBeats', false), mda_timepoints(res, 'CTRL', 'rigT_S', 3, '2000-01-01 12:00', [-60 10], ...
    'sampleID', 'H2', 'group', 'HTX', 'averageBeats', false), mda_timepoints(res, 'OME0.5uM', 'rigT_S', 2, ...
    '2000-01-02 12:00', [-60 10], 'sampleID', 'H3', 'averageBeats', false)};
PT = mda_poolTimepoints(res, 'name', 'test', 'labels', {'CTRL', 'OME0.5uM'});   %not T1, T6 of the checks above
S = PT.slices;
o = S(strcmp(S.treatment, 'OME0.5uM'), :); c = S(strcmp(S.treatment, 'CTRL'), :);
ka = find(strcmp(S.Properties.VariableNames, 'analysis'));
ok = check(ok, 'pool: slices table (treatment, substance, concentration, sample, slice, time point)', ...
    isequal(S.Properties.VariableNames(1:10), {'treatment', 'substance', 'concentration', 'concentrationUnit', ...
    'group', 'sampleID', 'sliceID', 'timePoint', 'offset_min', 'isBaseline'}) && height(S) == 8 && ...
    isequal(S.Properties.VariableNames(ka:ka+2), {'analysis', 'controlReference', 'nControlSlices'}) && ...
    strcmp(S.Properties.VariableNames{end}, 'beatsPerMinute_pctBaseline_vsControl') && ...
    ismember('treatmentTime', S.Properties.VariableNames) && ...
    all(strcmp(o.substance, 'OME')) && all(o.concentration == 0.5) && all(strcmp(o.concentrationUnit, 'uM')) && ...
    all(strcmp(c.substance, 'CTRL')) && all(isnan(c.concentration)) && all(strcmp(c.sliceID, 'rigT_S_ch3')) && ...
    isequal(unique(o.sliceID)', {'rigT_S_ch1', 'rigT_S_ch2'}) && isequal(o.timePoint(1:2)', {'-1 h', '+10 min'}) ...
    && isequal(S.isBaseline(1:2)', [1 0]) && isequal(sort(unique(o.group))', {'', 'HTX'}));
T = PT.treatments; r = T(strcmp(T.treatment, 'OME0.5uM') & T.offset_min == 10, :);
v = [15000 / mean(a0) 100 100];
ok = check(ok, 'pool: treatments (controls first, slices and samples)', ...
    isequal(T.treatment', {'CTRL', 'CTRL', 'OME0.5uM', 'OME0.5uM'}) && r.nSlices == 3 && r.nSamples == 2 && ...
    abs(r.amplitude_pctBaseline - mean(v)) < 1e-9 && abs(r.amplitude_pctBaseline_SEM - std(v) / sqrt(3)) < 1e-9 && ...
    abs(r.amplitude_pctBaseline_samples - ((v(1) + v(2)) / 2 + v(3)) / 2) < 1e-9);
Sm = PT.samples; C = PT.course;
r1 = o(strcmp(o.sliceID, 'rigT_S_ch1') & o.offset_min == 10, :);
ok = check(ok, 'pool: against the controls (OME: all controls, CTRL: own sample)', isequal(PT.controls, {'CTRL'}) ...
    && all(strcmp(o.controlReference, 'all controls')) && all(strcmp(c.controlReference, 'sample')) && ...
    r1.nControlSlices == 1 && abs(r1.amplitude_pctBaseline_vsControl - 15000 / mean(a0)) < 1e-9 && ...
    r1.diastolicForce_delta_vsControl == 20 && all(c.amplitude_pctBaseline_vsControl == 100));
ok = check(ok, 'pool: samples, course, analyses', height(Sm) == 6 && ...
    isequal(Sm.nSlices(strcmp(Sm.sampleID, 'H1'))', [2 2]) && isequal(unique(C.treatment)', {'CTRL', 'OME0.5uM'}) ...
    && C.amplitude_pctBaseline(strcmp(C.treatment, 'OME0.5uM') & C.minutes == -1) == 100 && ...
    all(strcmp(PT.analyses.status, 'pooled')));
d = fullfile(res, 'timepoints_pooled', 'test');
D = dir(d); D = sort({D(~startsWith({D.name}, '.')).name});
Dc = dir(fullfile(d, 'CTRL')); Dc = sort({Dc(~startsWith({Dc.name}, '.')).name});
[gg, mm, ee] = ndgrid({'timepoints', 'course'}, {'abs', 'norm'}, {'.png', '.fig'});
pass = strcmp(PT.folder, d) && isequal(D, {'CTRL', 'OME0.5uM', 'test.xlsx', 'treatments_abs.fig', ...
    'treatments_abs.png', 'treatments_norm.fig', 'treatments_norm.png', 'treatments_vsControl.fig', ...
    'treatments_vsControl.png'}) && ...
    isequal(Dc, sort(strcat('CTRL_', gg(:)', '_', mm(:)', ee(:)'))) && ...
    isequal(cellstr(sheetnames(fullfile(d, 'test.xlsx')))', {'slices', 'samples', 'treatments', 'course', ...
    'averageBeatsMean', 'analyses', 'info'});
ok = check(ok, 'pool: files (workbook, images per treatment, treatments_abs / _norm)', pass);
P2 = mda_poolTimepoints(TPs, 'write', false);
k = {'treatment', 'sampleID', 'sliceID', 'offset_min'};
A1 = sortrows(S, k); A2 = sortrows(P2.slices, k);
pass = true;
for cc = {'amplitude', 'amplitude_pctBaseline', 'diastolicForce_delta', 'amplitude_SEM', ...
        'amplitude_pctBaseline_vsControl', 'diastolicForce_delta_vsControl'}
    x1 = A1.(cc{1}); x2 = A2.(cc{1});
    pass = pass && isequal(isnan(x1), isnan(x2)) && max(abs(x1(~isnan(x1)) - x2(~isnan(x2)))) < 1e-9;
end
try
    mda_poolTimepoints(res, 'labels', {'nothing'}, 'write', false); pass = false;
catch
end
ok = check(ok, 'pool: TP structs give the same values; error without analyses', pass);
end


% =====================================================================================================================
function ok = check(ok, txt, pass)
if pass, fprintf('  ok    %s\n', txt); else, fprintf('  FAIL  %s\n', txt); end
ok = ok && pass;
end


function writeResults(res)
s = fullfile(res, 'expT', 'rigT_S');
recording(fullfile(s, '00'), 'rigT_S_0', '2000-01-01 06:00:00', 1, false);
recording(fullfile(s, '01'), 'rigT_S_1', '2000-01-02 06:00:00', 2, false);
recording(fullfile(s, '00'), 'rigT_S_0_par', '2000-01-01 11:00:00', 1, true);
files = {'expT/rigT_S_0.mdd'; 'expT/rigT_S_1.mdd'; 'expT/rigT_S_0_par.mdd'};
n = numel(files);
X = table(files, ones(n, 1), repmat({''}, n, 1), ones(n, 1), repmat({'ok'}, n, 1), repmat({'x'}, n, 1), ...
    repmat({'MATLAB'}, n, 1), repmat({''}, n, 1), repmat({'contractions=all'}, n, 1), repmat({''}, n, 1), ...
    ones(n, 1), ones(n, 1), repmat({''}, n, 1), repmat({''}, n, 1), 'VariableNames', {'file', 'bytes', 'modified', ...
    'logBytes', 'status', 'version', 'implementation', 'code', 'options', 'analyzed', 'seconds', 'nContractions', ...
    'outputs', 'message'});
writetable(X, fullfile(res, 'mda_index.csv'));
R = table(repmat({'rigT_S'}, 4, 1), [1; 1; 2; 3], [1; 2; 1; 1], {'A1'; 'A1'; ''; ''}, {'2000-01-01 10:00:01'; ...
    '2000-01-02 08:00:00'; '2000-01-01 10:00:01'; '2000-01-01 10:00:01'}, {'2000-01-02 07:00:00'; ...
    '2000-01-02 14:59:59'; '2000-01-02 14:59:59'; '2000-01-01 14:59:59'}, 'VariableNames', {'series', 'channel', ...
    'slice', 'sampleID', 'startTime', 'endTime'});
writetable(R, fullfile(res, 'expT', 'expT_slices.csv'));
end


function recording(d, n, start, day, parallel)
if ~isfolder(d), mkdir(d); end
rs = datetime(start, 'InputFormat', 'yyyy-MM-dd HH:mm:ss');
L = '86400'; if parallel, L = '3600'; end
writetable(table({'recordingStart'; 'fileLength_s'}, {start; L}, 'VariableNames', {'key', 'value'}), ...
    fullfile(d, [n '_info.csv']));
t0 = datetime(2000, 1, 1, 12, 0, 0);
beats = dateshift(rs, 'start', 'day') + hours(10) + seconds(1 + 2 * (0:8999)');      %10:00:01 .. 14:59:59, 0.5 Hz
ch = []; tt = NaT(0, 1); bt = {}; amp = []; ttp = []; dia = [];
for c = 1:3
    t = beats;
    if parallel
        if c ~= 1, continue; end
        t = t(t >= datetime(2000, 1, 1, 11, 0, 0) & t < datetime(2000, 1, 1, 13, 0, 0));
    end
    if c == 2 && day == 1
        t = t(~(t >= datetime(2000, 1, 1, 12, 9, 30) & t < datetime(2000, 1, 1, 12, 11, 0)));
    end
    if c == 3 && day == 2, continue; end
    switch c
        case 1, a = 150 * ones(numel(t), 1); if day == 1, a(t < t0) = 100; end
        case 2, a = 200 * ones(numel(t), 1);
        case 3
            a = 300 * ones(numel(t), 1);                %alternans 300 / 150 from 13:30
            if day == 1
                k = round((seconds(t - dateshift(t, 'start', 'day') - hours(10)) - 1) / 2);
                a(t >= datetime(2000, 1, 1, 13, 30, 0) & mod(k, 2) == 1) = 150;
            end
    end
    if parallel, a(:) = 999; end
    p = 0.12 * ones(numel(t), 1); p(a == 100) = 0.1;
    df = 50 * ones(numel(t), 1);
    if c == 1, df(:) = 30; if day == 1, df(t < t0) = 10; end, end
    ch = [ch; c * ones(numel(t), 1)]; tt = [tt; t]; bt = [bt; repmat({'stimulated'}, numel(t), 1)]; %#ok<AGROW>
    amp = [amp; a]; ttp = [ttp; p]; dia = [dia; df]; %#ok<AGROW>
    if c == 1 && day == 1 && ~parallel
        ch(end+1, 1) = 1; tt(end+1, 1) = datetime(2000, 1, 1, 11, 0, 30.5); bt{end+1, 1} = 'extra'; %#ok<AGROW>
        amp(end+1, 1) = 40; ttp(end+1, 1) = 0.1; dia(end+1, 1) = 10; %#ok<AGROW>
    end
end
[~, o] = sortrows([ch, datenum(tt)]); %#ok<DATNM>
ch = ch(o); tt = tt(o); bt = bt(o); amp = amp(o); ttp = ttp(o); dia = dia(o);
k = numel(ch);
sf = 0.5 * ones(k, 1); sf(strcmp(bt, 'extra')) = nan;
C = table(ch, cellstr(string(tt, 'yyyy-MM-dd HH:mm:ss.SSS')), bt, ones(k, 1), sf, sf, amp, ttp, dia, ...
    5000 * ones(k, 1), 'VariableNames', {'channel', 'clockTime', 'beatType', 'included', 'stimFrequency', ...
    'peakToPeakFrequency', 'amplitude', 'TTP90', 'diastolicForce', 'dFdtMax'});
C.t_peak = seconds(tt - rs); C.t_stim = C.t_peak - 0.12; C.t_stim(strcmp(bt, 'extra')) = nan;
writetable(C, fullfile(d, [n '_contractions.csv']));
% overview: 1-min medians per channel
w = dateshift(tt, 'start', 'minute');
[G, gc, gw] = findgroups(ch, w);
O = table(cellstr(string(gw, 'yyyy-MM-dd HH:mm:ss')), gc, repmat({'stimulated'}, numel(gc), 1), ...
    ones(numel(gc), 1), splitapply(@numel, amp, G), splitapply(@median, amp, G), splitapply(@median, ttp, G), ...
    splitapply(@median, dia, G), 5000 * ones(numel(gc), 1), 'VariableNames', {'window', 'channel', 'beatType', ...
    'included', 'nBeats', 'amplitude', 'TTP90', 'diastolicForce', 'dFdtMax'});
writetable(O, fullfile(d, [n '_overview.csv']));
if day == 1 && ~parallel
    writetable(table(2, {'2000-01-01 12:09:30'}, {'2000-01-01 12:11:00'}, {'chamber out'}, 'VariableNames', ...
        {'channel', 'clockFrom', 'clockTo', 'type'}), fullfile(d, [n '_gaps.csv']));
    writetable(table({'2000-01-01 12:11:00.000'}, 2, {'comment'}, {'medium exchange'}, 'VariableNames', ...
        {'clockTime', 'channel', 'category', 'text'}), fullfile(d, [n '_events.csv']));
    s0 = seconds(datetime(2000, 1, 1, 13, 59, 0) - rs);
    writetable(table({'PD'}, {'P1'}, 1, s0, s0 + 240, 'VariableNames', {'type', 'name', 'number', 'from', 'to'}), ...
        fullfile(d, [n '_protocols_protocols.csv']));
end
end
